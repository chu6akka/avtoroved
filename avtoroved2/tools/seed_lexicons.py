def main() -> None:
    written = 0
    for rel, words in LEXICONS.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(words) + "\n", encoding="utf-8")
        written += 1
    print(f"Создано словарей: {written}")


