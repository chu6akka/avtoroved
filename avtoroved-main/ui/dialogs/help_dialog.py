_SHORTCUTS = """
<h2>Горячие клавиши и сервис</h2>
<table cellpadding="6">
<tr><td><b>F1</b></td><td>это руководство</td></tr>
<tr><td><b>F4</b></td><td>справочник словарей (пласты и темы)</td></tr>
<tr><td><b>Ctrl+O</b></td><td>открыть файл в поле анализа</td></tr>
<tr><td><b>Ctrl+Enter</b></td><td>запустить анализ текста</td></tr>
<tr><td><b>F2 / F3</b></td><td>текст в отдельном окне / развернуть поле</td></tr>
<tr><td><b>Ctrl+1…0</b></td><td>переключение страниц</td></tr>
</table>

<h3>Меню</h3>
<ul>
<li><b>Файл → Обновить словарные базы</b> — явная загрузка свежих словарей
с бэкапом и фиксацией версии.</li>
<li><b>Сервис → Инспектор токенов</b> — карточка каждого слова: морфология,
частотность НКРЯ, регистровый слой, тональность, внешние словари.</li>
<li><b>Вид</b> — тёмная и светлая темы.</li>
</ul>

<h3>Если LanguageTool не подключается</h3>
<p>Нужна Java 8+ (adoptium.net). Программа ищет её в PATH, в
<i>config.json</i> (ключ <code>java_home</code>), в JAVA_HOME, в реестре
и типовых каталогах. Проверка одной командой:
<code>python scripts/check_lt.py</code>. Без Java работают только
собственные правила пунктуации — это видно в журнале анализа.</p>
"""


class HelpDialog(QDialog):
    """Руководство по программе."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Руководство — Автороведческий анализатор")
        self.resize(860, 640)

        layout = QVBoxLayout(self)
        tabs = QTabWidget()
        for title, html in (("Порядок работы", _WORKFLOW),
                            ("Принципы и границы", _PRINCIPLES),
                            ("Клавиши и сервис", _SHORTCUTS)):
            page = QWidget()
            v = QVBoxLayout(page)
            v.setContentsMargins(0, 0, 0, 0)
            browser = QTextBrowser()
            browser.setOpenExternalLinks(True)
            browser.setHtml(html)
            v.addWidget(browser)
            tabs.addTab(page, title)
        layout.addWidget(tabs)

        row = QHBoxLayout()
        row.addStretch()
        btn = QPushButton("Закрыть")
        btn.clicked.connect(self.accept)
        row.addWidget(btn)
        layout.addLayout(row)
